const { spawn } = require('child_process');
const http = require('http');
const fs = require('fs');
const { downloadChoiceSheet } = require('../src/utils/exportChoiceData.js');

async function test() {
  const edgePath = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
  const userDataDir = 'C:\\Users\\Raju\\.gemini\\antigravity\\brain\\20845224-7465-4d56-9c11-406ea7005c30\\scratch\\edge_test_sheet';
  if (!fs.existsSync(userDataDir)) {
    fs.mkdirSync(userDataDir, { recursive: true });
  }

  // Let's trigger download in the browser and see what file is generated
  const port = 9576;
  const edge = spawn(edgePath, [
    '--headless=new',
    `--remote-debugging-port=${port}`,
    `--user-data-dir=${userDataDir}`,
    '--disable-gpu',
    '--no-sandbox',
    '--window-size=1440,1200',
    'http://localhost:5173'
  ]);

  await new Promise(r => setTimeout(r, 2500));

  const tabs = await new Promise((resolve, reject) => {
    http.get(`http://127.0.0.1:${port}/json/list`, res => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => resolve(JSON.parse(data)));
    }).on('error', reject);
  });

  const page = tabs.find(t => t.url.includes('localhost:5173')) || tabs[0];
  const ws = new WebSocket(page.webSocketDebuggerUrl);

  let id = 1;
  const pending = new Map();

  ws.onmessage = (event) => {
    const msg = JSON.parse(event.data);
    if (msg.id && pending.has(msg.id)) {
      const { resolve } = pending.get(msg.id);
      pending.delete(msg.id);
      resolve(msg.result);
    }
  };

  const send = (method, params = {}) => {
    return new Promise((resolve, reject) => {
      const reqId = id++;
      pending.set(reqId, { resolve, reject });
      ws.send(JSON.stringify({ id: reqId, method, params }));
    });
  };

  await new Promise(r => ws.onopen = r);
  await send('Page.enable');

  const evalJs = async (expr) => {
    const res = await send('Runtime.evaluate', { expression: expr, returnByValue: true, awaitPromise: true });
    return res?.result?.value;
  };

  // Wait for initial load
  for (let i = 0; i < 20; i++) {
    const btns = await evalJs("document.querySelectorAll('button').length");
    if (btns > 10) break;
    await new Promise(r => setTimeout(r, 250));
  }

  // Set candidate profile: CSAB, CRL 38291
  await evalJs(`
    const btns = Array.from(document.querySelectorAll('button'));
    const csabBtn = btns.find(b => b.innerText.includes('CSAB Special Round 1/2') || b.innerText.includes('CSAB Special'));
    if (csabBtn) csabBtn.click();
  `);
  await new Promise(r => setTimeout(r, 1200));

  // Get the HTML content generated by downloadChoiceSheet directly in browser
  const sheetHtml = await evalJs(`
    (() => {
      // Find the download button at end of colleges and inspect what Blob it creates
      const downloadBtn = Array.from(document.querySelectorAll('#edit-choices-section button')).find(b => b.innerText.includes('Download'));
      return downloadBtn ? 'found' : 'not found';
    })()
  `);
  console.log('Download button status:', sheetHtml);

  // We can also extract the exact HTML output
  const generatedHtml = await evalJs(`
    (() => {
      // We can grab the function and get its HTML by intercepting URL.createObjectURL
      let capturedBlob = null;
      const origCreate = URL.createObjectURL;
      URL.createObjectURL = (blob) => {
        capturedBlob = blob;
        return origCreate(blob);
      };
      const downloadBtn = Array.from(document.querySelectorAll('#edit-choices-section button')).find(b => b.innerText.includes('Download'));
      if (downloadBtn) downloadBtn.click();
      URL.createObjectURL = origCreate;
      if (capturedBlob) {
        return new Promise(resolve => {
          const reader = new FileReader();
          reader.onload = () => resolve(reader.result);
          reader.readAsText(capturedBlob);
        });
      }
      return 'no blob captured';
    })()
  `);

  if (generatedHtml && generatedHtml.length > 100) {
    fs.writeFileSync('C:\\Users\\Raju\\.gemini\\antigravity\\brain\\20845224-7465-4d56-9c11-406ea7005c30\\scratch\\downloaded_choice_sheet.html', generatedHtml);
    console.log('Saved intercepted choice sheet HTML to scratch/downloaded_choice_sheet.html (size: ' + generatedHtml.length + ' bytes)');
  }

  await send('Browser.close');
  edge.kill();

  // Now open this downloaded HTML sheet in headless edge and take a screenshot!
  const sheetEdge = spawn(edgePath, [
    '--headless=new',
    `--remote-debugging-port=9577`,
    `--user-data-dir=${userDataDir}2`,
    '--disable-gpu',
    '--no-sandbox',
    '--no-first-run',
    '--no-default-browser-check',
    '--window-size=1440,1200',
    'file:///C:/Users/Raju/.gemini/antigravity/brain/20845224-7465-4d56-9c11-406ea7005c30/scratch/downloaded_choice_sheet.html'
  ]);
  await new Promise(r => setTimeout(r, 2000));

  const sheetTabs = await new Promise((resolve, reject) => {
    http.get(`http://127.0.0.1:9577/json/list`, res => {
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => resolve(JSON.parse(data)));
    }).on('error', reject);
  });

  const sheetWs = new WebSocket(sheetTabs[0].webSocketDebuggerUrl);
  let sid = 1;
  const sPending = new Map();
  sheetWs.onmessage = (event) => {
    const msg = JSON.parse(event.data);
    if (msg.id && sPending.has(msg.id)) {
      const { resolve } = sPending.get(msg.id);
      sPending.delete(msg.id);
      resolve(msg.result);
    }
  };
  const sSend = (method, params = {}) => new Promise(resolve => {
    const reqId = sid++;
    sPending.set(reqId, { resolve });
    sheetWs.send(JSON.stringify({ id: reqId, method, params }));
  });
  await new Promise(r => sheetWs.onopen = r);
  await sSend('Page.enable');
  await new Promise(r => setTimeout(r, 600));

  const sheetScreen = await sSend('Page.captureScreenshot', { format: 'png' });
  fs.writeFileSync('C:\\Users\\Raju\\.gemini\\antigravity\\brain\\20845224-7465-4d56-9c11-406ea7005c30\\screenshot_downloaded_choice_sheet_preview.png', Buffer.from(sheetScreen.data, 'base64'));
  console.log('Saved screenshot_downloaded_choice_sheet_preview.png');

  await sSend('Browser.close');
  sheetEdge.kill();
  process.exit(0);
}

test().catch(err => {
  console.error(err);
  process.exit(1);
});
